# test-upgrade-config.sh
# ------------------------------------------------------------------------------
# Parses the two package-management files install.sh writes on every runner
# instance, the way the tools that read them on the instance do.
#
# Both files are written before install.sh's first apt-get, so a mistake in
# either one does not stay local: a needrestart snippet that does not parse
# makes needrestart die after every dpkg run, and an apt.conf.d file with a
# syntax error makes every later apt-get in install.sh fail, and with it the
# whole instance build. This catches both before an instance is built.
#
# It extracts the heredoc bodies straight out of install.sh, evaluates the
# needrestart snippet with the loop the stock /etc/needrestart/needrestart.conf
# uses for its conf.d files, and parses the apt snippet with apt-config when the
# machine has it. It needs perl, but neither root nor needrestart.
#
#   ./hack/test-upgrade-config.sh      # from the repository root
#   make test-upgrade-config
# ------------------------------------------------------------------------------

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="${ROOT}/install.sh"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/ogrm-upgrade-config-test.XXXXXX")"
trap 'rm -rf "${WORK}"' EXIT

# --- extract the files under test ---------------------------------------------
# extract <delimiter> <file> writes the body of install.sh's <<'<delimiter>'
# heredoc to <file>, and fails when there is none.
extract() {
  awk -v open="<<'$1'" -v delim="$1" '
    index($0, open) { inside = 1; next }
    $0 == delim     { inside = 0 }
    inside' "${SRC}" > "$2"
  if [[ ! -s "$2" ]]; then
    echo "FAIL: could not extract the $1 heredoc from ${SRC} (did its delimiter change?)" >&2
    exit 1
  fi
}

NEEDRESTART="${WORK}/99-ogrm-runner.conf"
APTCONF="${WORK}/99-ogrm-no-unattended-upgrades"
extract NEEDRESTART "${NEEDRESTART}"
extract APTCONF "${APTCONF}"

# The stock needrestart.conf sets override_rc (docker is one of its entries),
# then evaluates every conf.d/*.conf with exactly this eval/die pair. sel is how
# needrestart picks a service: the first override_rc regex that matches decides,
# and a service no entry matches is restarted.
HARNESS="$(cat <<'PERL'
our %nrconf = (override_rc => { qr(^docker) => 0 });
my $fn = shift;
eval do { local(@ARGV, $/) = $fn; <> };
die "Error parsing $fn: $@" if $@;
sub sel { my $rc = shift; for my $re (sort keys %{$nrconf{override_rc}}) { return $nrconf{override_rc}{$re} if $rc =~ /$re/ } return 1 }
print sel($_), "\n" for @ARGV;
PERL
)"

# --- harness ------------------------------------------------------------------
cases=0
case_name=""

start() { case_name="$1"; cases=$((cases + 1)); printf '  %s\n' "${case_name}"; }

fail() {
  printf '\nFAIL (%s): %s\n' "${case_name}" "$1" >&2
  exit 1
}

echo "Testing the package-upgrade config generated by install.sh:"

# --- needrestart --------------------------------------------------------------
UNITS=(actions.runner.C5C3-cobaltcore.ogrm-c5c3-006.service docker.service ssh.service)

start "needrestart evaluates the snippet the way needrestart.conf does"
command -v perl >/dev/null 2>&1 \
  || fail "perl not found; it is needed to evaluate the needrestart snippet"
if ! out="$(perl -e "${HARNESS}" "${NEEDRESTART}" "${UNITS[@]}" 2>&1)"; then
  fail "needrestart would die after every dpkg run: ${out}"
fi
mapfile -t selected <<< "${out}"

# expect_selected <index> <value> checks what sel returned for UNITS[index].
expect_selected() {
  printf '    %s -> %s\n' "${UNITS[$1]}" "${selected[$1]:-}"
  [[ "${selected[$1]:-}" == "$2" ]] || fail "needrestart selects ${UNITS[$1]} with ${selected[$1]:-nothing}, expected $2"
}

start "needrestart leaves the runner service alone"
expect_selected 0 0

start "needrestart keeps its stock docker exemption"
expect_selected 1 0

start "needrestart still restarts every other service"
expect_selected 2 1

# --- apt ----------------------------------------------------------------------
# Parsed before the literal is checked, so a malformed file shows apt's own
# error rather than only a missing line.
if command -v apt-config >/dev/null 2>&1; then
  start "apt parses the snippet"
  if ! parsed="$(apt-config -c "${APTCONF}" shell v APT::Periodic::Unattended-Upgrade 2>&1)"; then
    fail "apt rejects the snippet, so every later apt-get in install.sh would fail: ${parsed}"
  fi
  [[ "${parsed}" == "v='0'" ]] \
    || fail "apt reads APT::Periodic::Unattended-Upgrade as ${parsed:-nothing}, expected v='0'"
else
  echo "  skip: apt-config not found, syntax not parsed"
fi

start "the snippet turns unattended upgrades off"
grep -qxF 'APT::Periodic::Unattended-Upgrade "0";' "${APTCONF}" \
  || fail "the apt snippet has no line APT::Periodic::Unattended-Upgrade \"0\";"

printf '\nok - %d cases passed\n' "${cases}"
